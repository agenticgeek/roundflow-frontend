import type { FormEvent } from 'react'
import { useMemo, useRef, useState } from 'react'
import type { Round, ServiceArea } from '@/api/types'
import type { PropertyRecord } from '@/types/setup-wizard'
import { setupWizardContent } from '@/content/setup-wizard'
import { FieldError } from '@/components/ui'
import {
  ChoiceChip,
  InfoNote,
  OptionCard,
  WarningNote,
  WizardCard,
  WizardStepTitle,
} from '@/components/setup-wizard/WizardParts'
import { primaryButtonClass } from '@/components/setup-wizard/wizard-styles'
import { firstRoundDate, formatShortDate, todayIso } from '@/lib/round-dates'
import { fillCopy } from '@/lib/utils'

export interface GoLiveInput {
  generateAll: boolean
  roundIds: string[]
  startDate: string
}

export interface GoLiveSummary {
  rounds: number
  visits: number
  startDate: string
}

interface ActivateStepProps {
  rounds: Round[]
  areas: ServiceArea[]
  properties: PropertyRecord[]
  /** Visits already generated by an earlier activation — they're never generated twice. */
  visitsGenerated: number
  working: boolean
  onGoLive: (input: GoLiveInput, summary: GoLiveSummary) => Promise<void>
  /** Opens the Rounds step to fix areas without rounds / unplaced properties. */
  onFixRounds: () => void
}

function BoltIcon() {
  return (
    <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8" aria-hidden="true">
      <path d="M13 2.5 4.5 13.5H12l-1 8 8.5-11H12l1-8Z" strokeLinejoin="round" />
    </svg>
  )
}

function CalendarIcon() {
  return (
    <svg viewBox="0 0 20 20" fill="none" stroke="currentColor" strokeWidth="1.6" className="h-4 w-4 text-muted" aria-hidden="true">
      <rect x="3" y="4.5" width="14" height="12.5" rx="1.5" />
      <path d="M3 8.5h14M7 3v3M13 3v3" strokeLinecap="round" />
    </svg>
  )
}

function PlayIcon() {
  return (
    <svg viewBox="0 0 16 16" fill="currentColor" className="h-3.5 w-3.5" aria-hidden="true">
      <path d="M4.5 2.8v10.4a.6.6 0 0 0 .9.5l8-5.2a.6.6 0 0 0 0-1L5.4 2.3a.6.6 0 0 0-.9.5Z" />
    </svg>
  )
}

export function ActivateStep({
  rounds,
  areas,
  properties,
  visitsGenerated,
  working,
  onGoLive,
  onFixRounds,
}: ActivateStepProps) {
  const content = setupWizardContent.activate
  const { preview } = content
  const roundsContent = setupWizardContent.rounds

  const savedRounds = useMemo(() => rounds.filter((round): round is Round & { id: string } => Boolean(round.id)), [rounds])
  const [generateAll, setGenerateAll] = useState(true)
  const [pickedIds, setPickedIds] = useState<string[]>(() => savedRounds.map((round) => round.id))
  const [startDate, setStartDate] = useState(todayIso)
  const [error, setError] = useState<string | null>(null)
  const dateInputRef = useRef<HTMLInputElement>(null)

  const alreadyGenerated = visitsGenerated > 0
  const selectedRounds = generateAll ? savedRounds : savedRounds.filter((round) => pickedIds.includes(round.id))

  const propertiesPerRound = useMemo(() => {
    const counts = new Map<string, number>()
    for (const property of properties) {
      if (property.round) counts.set(property.round, (counts.get(property.round) ?? 0) + 1)
    }
    return counts
  }, [properties])

  const rows = selectedRounds.map((round) => {
    const count = propertiesPerRound.get(round.id) ?? 0
    return {
      round,
      day: roundsContent.days.find((day) => day.value === round.defaultDay)?.label ?? '—',
      frequency: roundsContent.frequencies.find((option) => option.value === round.frequency)?.label ?? '—',
      properties: count,
      firstVisit: firstRoundDate(startDate, round.defaultDay),
      visits: count,
    }
  })
  const totalVisits = rows.reduce((sum, row) => sum + row.visits, 0)
  const areaName = (id: string | null | undefined) => areas.find((area) => area.id === id)?.name ?? ''
  const selectedAreaNames = [...new Set(selectedRounds.map((round) => areaName(round.serviceAreaId)).filter(Boolean))]

  const areasWithoutRounds = areas
    .filter((area) => area.id && !savedRounds.some((round) => round.serviceAreaId === area.id))
    .map((area) => area.name ?? '')
  const unplaced = properties.filter((property) => !property.round).length
  const warningParts = [
    areasWithoutRounds.length > 0 ? fillCopy(preview.noAreaRounds, { areas: areasWithoutRounds.join(', ') }) : null,
    unplaced > 0 ? fillCopy(preview.unassignedProperties, { count: unplaced }) : null,
  ].filter(Boolean)

  function togglePicked(id: string) {
    setPickedIds((prev) => (prev.includes(id) ? prev.filter((item) => item !== id) : [...prev, id]))
    setError(null)
  }

  async function goLive() {
    if (!generateAll && pickedIds.length === 0) {
      setError(content.validation.roundsRequired)
      return
    }
    if (!alreadyGenerated && totalVisits === 0) {
      setError(content.validation.noVisits)
      return
    }
    setError(null)
    try {
      await onGoLive(
        { generateAll, roundIds: selectedRounds.map((round) => round.id), startDate },
        { rounds: selectedRounds.length, visits: alreadyGenerated ? visitsGenerated : totalVisits, startDate },
      )
    } catch (err) {
      setError(err instanceof Error ? err.message : String(err))
    }
  }

  function handleSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault()
    void goLive()
  }

  const isToday = startDate === todayIso()

  return (
    <form id="setup-wizard-step-form" onSubmit={handleSubmit} noValidate className="space-y-6">
      <WizardStepTitle icon={<BoltIcon />} title={content.heading} subtitle={content.subheading} />

      {alreadyGenerated ? <InfoNote>{fillCopy(content.alreadyGenerated, { count: visitsGenerated })}</InfoNote> : null}

      <WizardCard heading={content.sections.rounds}>
        <div role="radiogroup" aria-label={content.sections.rounds} className="grid gap-4 sm:grid-cols-2">
          <OptionCard
            selected={generateAll}
            onSelect={() => setGenerateAll(true)}
            title={content.scope.all.label}
            description={content.scope.all.description}
          />
          <OptionCard
            selected={!generateAll}
            onSelect={() => setGenerateAll(false)}
            title={content.scope.selected.label}
            description={content.scope.selected.description}
          />
        </div>
        {generateAll ? null : (
          <div className="mt-5">
            <p className="mb-2 text-sm font-medium text-foreground">{content.scope.pickRounds}</p>
            <div className="flex flex-wrap gap-2">
              {savedRounds.map((round) => (
                <ChoiceChip
                  key={round.id}
                  label={round.name ?? ''}
                  selected={pickedIds.includes(round.id)}
                  onClick={() => togglePicked(round.id)}
                />
              ))}
            </div>
          </div>
        )}
      </WizardCard>

      <WizardCard heading={content.sections.startDate}>
        <p className="mb-2 text-sm font-medium text-foreground">{content.startDate.label}</p>
        <label className="relative flex cursor-pointer items-center gap-3 rounded-xl border border-border bg-background px-4 py-3 text-[15px] text-foreground transition-colors focus-within:border-foreground">
          <CalendarIcon />
          <span>
            {formatShortDate(startDate, true)} {isToday ? content.startDate.today : null}
          </span>
          {/* The real date input sits on top, invisible, so the native picker opens on click. */}
          <input
            ref={dateInputRef}
            type="date"
            value={startDate}
            min={todayIso()}
            onChange={(event) => event.target.value && setStartDate(event.target.value)}
            onClick={() => dateInputRef.current?.showPicker?.()}
            aria-label={content.startDate.label}
            className="absolute inset-0 cursor-pointer opacity-0"
          />
        </label>
        <p className="mt-2 text-sm text-muted">{content.startDate.hint}</p>
      </WizardCard>

      <WizardCard heading={content.sections.preview}>
        {rows.length === 0 ? (
          <p className="rounded-xl border border-dashed border-border px-4 py-6 text-center text-sm text-muted">{preview.none}</p>
        ) : (
          <div className="overflow-x-auto rounded-xl border border-border">
            <table className="w-full min-w-[40rem] text-left text-sm sm:text-[15px]">
              <thead className="bg-foreground/[0.025] text-sm text-muted">
                <tr>
                  <th scope="col" className="px-5 py-3 font-normal">{preview.columns.round}</th>
                  <th scope="col" className="px-5 py-3 font-normal">{preview.columns.day}</th>
                  <th scope="col" className="px-5 py-3 font-normal">{preview.columns.frequency}</th>
                  <th scope="col" className="px-5 py-3 font-normal">{preview.columns.properties}</th>
                  <th scope="col" className="px-5 py-3 font-normal">{preview.columns.firstVisit}</th>
                  <th scope="col" className="px-5 py-3 font-normal">{preview.columns.visits}</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-border">
                {rows.map((row) => (
                  <tr key={row.round.id}>
                    <td className="px-5 py-3.5 text-foreground">{row.round.name}</td>
                    <td className="px-5 py-3.5 text-foreground">{row.day}</td>
                    <td className="px-5 py-3.5 text-foreground">{row.frequency}</td>
                    <td className="px-5 py-3.5 text-foreground">{row.properties}</td>
                    <td className="px-5 py-3.5 whitespace-nowrap text-foreground">
                      {row.firstVisit ? formatShortDate(row.firstVisit) : '—'}
                    </td>
                    <td className="px-5 py-3.5 text-foreground">{row.visits}</td>
                  </tr>
                ))}
              </tbody>
              <tfoot className="border-t border-border bg-foreground/[0.025]">
                <tr>
                  <td colSpan={3} className="px-5 py-3.5 text-foreground">
                    {fillCopy(preview.footerRounds, { count: rows.length, areas: selectedAreaNames.join(', ') })}
                  </td>
                  <td colSpan={3} className="px-5 py-3.5 text-right font-semibold text-foreground">
                    {fillCopy(preview.footerVisits, { count: totalVisits })}
                  </td>
                </tr>
              </tfoot>
            </table>
          </div>
        )}

        {warningParts.length > 0 ? (
          <WarningNote className="mt-5">
            {warningParts.join(', and ')}
            {preview.warningSuffix}{' '}
            <button type="button" onClick={onFixRounds} className="font-medium underline-offset-2 hover:underline">
              {preview.fixNow}
            </button>
          </WarningNote>
        ) : null}

        <InfoNote className="mt-4">{preview.technicianInfo}</InfoNote>
      </WizardCard>

      <WizardCard tone="accent">
        <div className="flex flex-wrap items-center justify-between gap-4">
          <div>
            <h3 className="text-base font-semibold text-foreground sm:text-lg">{content.ready.heading}</h3>
            <p className="mt-1 text-sm text-muted sm:text-[15px]">
              {fillCopy(content.ready.description, { count: alreadyGenerated ? visitsGenerated : totalVisits })}
            </p>
          </div>
          <button type="button" onClick={() => void goLive()} disabled={working} className={primaryButtonClass}>
            <PlayIcon />
            {working ? content.ready.working : alreadyGenerated ? content.ready.buttonGoLive : content.ready.button}
          </button>
        </div>
        {error ? <FieldError message={error} /> : null}
      </WizardCard>
    </form>
  )
}
